export const locales = ['en', 'mr'] as const;
export type Locale = (typeof locales)[number];
export const isLocale = (v: string): v is Locale => (locales as readonly string[]).includes(v);

/** A bilingual string. */
export type L = { en: string; mr: string };
export const tx = (l: L, lang: Locale) => l[lang] || l.en;

/** Language-prefixed path. Portal routes are language-neutral. */
export const href = (lang: Locale, path = '/') => {
  if (path.startsWith('/portal') || path.startsWith('http')) return path;
  const clean = path.startsWith('/') ? path : `/${path}`;
  return `/${lang}${clean === '/' ? '/' : clean}`;
};

const dateFmt: Record<Locale, string> = { en: 'en-IN', mr: 'mr-IN' };
export const formatDate = (iso: string, lang: Locale, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short', year: 'numeric' }) =>
  new Date(iso + (iso.length === 10 ? 'T00:00:00' : '')).toLocaleDateString(dateFmt[lang], opts);

